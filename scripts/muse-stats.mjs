// Regenerates docs/MUSE.md: how much of the repo Muse Code wrote, from git
// history (commits on HEAD) and the GitHub API via gh (merged PRs).
// Usage: npm run muse:stats (needs gh signed in). Plain Node, no dependencies.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TRAILER = 'Co-authored-by: Muse Code (Meta) <muse-code@agents.noreply.invalid>';
const OUT = 'docs/MUSE.md';
const REPO = 'martinmw13/LectorIA-meta';
const BOT = 'github-actions[bot]';
// Source code: what "most of the code" means. Transcripts (agent-logs/),
// vendored skills (.agents/), lockfiles and book data are counted only in the
// all-files row.
export const SOURCE_DIRS = ['app/', 'core/', 'pipeline/', 'server/', 'scripts/'];

// Rescue commits (a `Rescue:` line, see RESCUE_LOG.md) are not Muse work even
// when an older hook also stamped the trailer on them.
export function isMuse(message) {
  const lines = message.split('\n').map((line) => line.trim());
  return lines.includes(TRAILER) && !lines.some((line) => line.startsWith('Rescue:'));
}

// Parses `git log --format=%x00%H%x1f%an%x1f%cd%x1f%B%x1e --numstat` output.
export function parseLog(text) {
  return text.split('\0').filter(Boolean).map((chunk) => {
    const [head, numstat = ''] = chunk.split('\x1e');
    const [sha, author, date, message] = head.split('\x1f');
    const files = numstat.split('\n').filter((l) => l.includes('\t')).map((l) => {
      const [added, removed, path] = l.split('\t');
      // Binary files show "-": no line counts.
      return { added: Number(added) || 0, removed: Number(removed) || 0, path };
    });
    return { sha, author, date, muse: isMuse(message), files };
  });
}

export function tally(commits, keep = () => true) {
  const out = { commits: 0, added: 0, removed: 0 };
  for (const c of commits) {
    out.commits += 1;
    for (const f of c.files) if (keep(f.path)) { out.added += f.added; out.removed += f.removed; }
  }
  return out;
}

const isSource = (path) => SOURCE_DIRS.some((d) => path.startsWith(d));
const fmt = (n) => n.toLocaleString('en-US');
const pct = (a, b) => (b === 0 ? '0%' : `${Math.round((100 * a) / b)}%`);

export function render({ commits, prs }) {
  const own = commits.filter((c) => c.author !== BOT);
  const muse = own.filter((c) => c.muse);
  const other = own.filter((c) => !c.muse);
  const all = { muse: tally(muse), other: tally(other) };
  const src = { muse: tally(muse, isSource), other: tally(other, isSource) };
  const dates = muse.map((c) => c.date).sort();
  const lines = [
    '# Built with Meta Muse',
    '',
    `Generated by \`npm run muse:stats\` (scripts/muse-stats.mjs) from git history and the GitHub API. Do not edit by hand; the \`muse-stats\` workflow refreshes it on every push to main.`,
    '',
    `A Muse commit is a non-merge commit on main that carries the trailer \`${TRAILER}\`. Commits without it are rescues by other tools, logged in [RESCUE_LOG.md](../RESCUE_LOG.md).`,
    '',
    '## Commits',
    '',
    `- Muse commits: ${fmt(muse.length)} of ${fmt(own.length)} non-merge commits (${pct(muse.length, own.length)}).`,
    `- Date range (UTC-3): ${dates[0] ?? 'n/a'} to ${dates.at(-1) ?? 'n/a'}.`,
    '',
    '## Lines',
    '',
    '| Scope | Muse added | Muse removed | Other added | Other removed | Muse share of added |',
    '| --- | --- | --- | --- | --- | --- |',
    `| Source code (${SOURCE_DIRS.map((d) => `\`${d}\``).join(', ')}) | ${fmt(src.muse.added)} | ${fmt(src.muse.removed)} | ${fmt(src.other.added)} | ${fmt(src.other.removed)} | ${pct(src.muse.added, src.muse.added + src.other.added)} |`,
    `| All files | ${fmt(all.muse.added)} | ${fmt(all.muse.removed)} | ${fmt(all.other.added)} | ${fmt(all.other.removed)} | ${pct(all.muse.added, all.muse.added + all.other.added)} |`,
    '',
    'All files includes the Muse Code session transcripts in `agent-logs/`, the vendored skills in `.agents/` and `package-lock.json`.',
    '',
    '## Pull requests',
    '',
    `${prs.length} merged PRs contain Muse commits. Each carries the \`Muse Code\` label.`,
    '',
    '| PR | Title | Merged (UTC-3) | Muse commits |',
    '| --- | --- | --- | --- |',
    ...prs.map((p) => `| [#${p.number}](https://github.com/${REPO}/pull/${p.number}) | ${p.title.replaceAll('|', '\\|')} | ${p.merged} | ${p.museCommits} of ${p.commits} |`),
    '',
  ];
  return lines.join('\n');
}

const tz = { ...process.env, TZ: 'America/Buenos_Aires' };
const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', env: tz, maxBuffer: 1 << 28 });
const localDate = (iso) => new Date(iso).toLocaleDateString('en-CA', { timeZone: 'America/Buenos_Aires' });

function loadPrs() {
  const list = JSON.parse(run('gh', ['pr', 'list', '-R', REPO, '--state', 'merged', '--limit', '1000', '--json', 'number,title,mergedAt']));
  const prs = [];
  for (const pr of list.sort((a, b) => a.number - b.number)) {
    const pages = JSON.parse(run('gh', ['api', '--paginate', '--slurp', `repos/${REPO}/pulls/${pr.number}/commits?per_page=100`]));
    const messages = pages.flat().map((c) => c.commit.message);
    const museCommits = messages.filter(isMuse).length;
    if (museCommits > 0) prs.push({ number: pr.number, title: pr.title, merged: localDate(pr.mergedAt), commits: messages.length, museCommits });
  }
  return prs;
}

function main() {
  const log = run('git', ['log', '--no-merges', '--date=format-local:%Y-%m-%d', '--format=%x00%H%x1f%an%x1f%cd%x1f%B%x1e', '--numstat', 'HEAD']);
  const md = render({ commits: parseLog(log), prs: loadPrs() });
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
